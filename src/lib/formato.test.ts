import { describe, expect, it } from 'vitest';
import { lerValor } from './formato';

describe('lerValor', () => {
  it.each([
    ['1000000', 1_000_000],
    ['1.000.000', 1_000_000],
    ['1.000.000,00', 1_000_000],
    ['R$ 1.000.000,50', 1_000_000.5],
    ['1,000,000', 1_000_000],
    ['1 milhão', 1_000_000],
    ['1 milhao', 1_000_000],
    ['1,5 mi', 1_500_000],
    ['2 milhões', 2_000_000],
    ['500 mil', 500_000],
    ['500.000', 500_000],
    ['500,000', 500_000],
    ['7,20', 7.2],
    ['3.36', 3.36],
    ['0', 0],
  ])('"%s" → %d', (s, v) => expect(lerValor(s)).toBe(v));

  it.each(['', 'abc', '1.2.3,4,5', '-100'])('"%s" não é valor', (s) => expect(lerValor(s)).toBeNull());
});
